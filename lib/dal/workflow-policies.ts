export async function listWorkflowPolicies(orgId: string, executor: Db | Tx = db) {
  return executor.select().from(workflowPolicies).where(eq(workflowPolicies.orgId, orgId));
}
export async function workflowPoliciesForPlacement(placement: PolicyPlacement, executor: Db | Tx = db) {
  const [policies, attachments] = await Promise.all([
    listWorkflowPolicies(placement.orgId, executor),
    executor.select().from(workflowPolicyAttachments).where(eq(workflowPolicyAttachments.orgId, placement.orgId)),
  ]);
  return resolvePolicyApplications(policies, attachments, placement);
}

/** Keep snapshots and actual subtask creation atomic, serialized by the parent row lock. */
export async function materializePolicies(tx: Tx, orgId: string, taskId: string, actorId: string, now: Date) {
  const [parent] = await tx.select().from(tasks).where(and(eq(tasks.orgId, orgId), eq(tasks.id, taskId))).for("update");
  if (!parent || parent.workflowPolicyId !== null) return;
  const goalIds = parent.goalId ? [parent.goalId] : [];
  if (parent.goalId) {
    const [goal] = await tx.select({ parent: goals.parentGoalId }).from(goals).where(and(eq(goals.orgId, orgId), eq(goals.id, parent.goalId)));
    if (goal?.parent) goalIds.push(goal.parent);
  }
  const applications = await workflowPoliciesForPlacement({ orgId, taskId, projectId: parent.projectId, goalIds }, tx);
  const items = addPolicySnapshots(parent.policyChecklist, applications).map((item) => ({ ...item }));
  const live = isLive(parent);
  if (parent.parentTaskId === null && live) {
    const assignment = await assignmentOf(tx, parent.id);
    for (const item of items) {
      if (!item.policyId || !item.policyTemplateId) continue;
      const [existing] = await tx.select({ id: tasks.id }).from(tasks).where(and(eq(tasks.orgId, orgId), eq(tasks.parentTaskId, parent.id), eq(tasks.workflowPolicyChecklistItemId, item.id)));
      if (existing) {
        item.generatedSubtaskId = existing.id;
        await tx.update(tasks).set({ proposalStatus: null }).where(eq(tasks.id, existing.id));
        continue;
      }
      const [child] = await tx.insert(tasks).values({
        orgId, projectId: parent.projectId, goalId: parent.goalId, parentTaskId: parent.id,
        title: item.label, description: "Required by " + item.policyName + ". Tick and sign on the parent task.",
        createdBy: parent.createdBy, priority: parent.priority,
        workflowPolicyId: item.policyId, workflowPolicyTemplateId: item.policyTemplateId,
        workflowPolicyName: item.policyName, workflowPolicyChecklistItemId: item.id,
        createdAt: now, updatedAt: now,
      }).returning({ id: tasks.id });
      item.generatedSubtaskId = child.id;
      await applyAssignment(tx, child.id, actorId, [], assignment, now);
      await recordActivity(tx, { orgId, taskId: child.id, actorId }, [{ kind: "created", after: { title: item.label, policyId: item.policyId }, note: "Generated by a workflow policy." }], now);
    }
  } else if (!live) {
    for (const item of items) if (item.generatedSubtaskId) await tx.update(tasks).set({ proposalStatus: "local" }).where(and(eq(tasks.orgId, orgId), eq(tasks.id, item.generatedSubtaskId), eq(tasks.parentTaskId, parent.id)));
  }
  if (JSON.stringify(items) !== JSON.stringify(parent.policyChecklist)) {
    await tx.update(tasks).set({ policyChecklist: items, updatedAt: now }).where(and(eq(tasks.orgId, orgId), eq(tasks.id, taskId)));
  }
}

export async function attachTaskPolicies(tx: Tx, orgId: string, taskId: string, ids: string[], actorId: string, now: Date) {
  const policies = await listWorkflowPolicies(orgId, tx);
  for (const policyId of new Set(ids)) {
    if (!policies.some((p) => p.id === policyId)) throw new GuardError("not_found", "That policy is not in this workspace.");
    await tx.insert(workflowPolicyAttachments).values({ orgId, policyId, scopeKind: "task", scopeId: taskId, createdBy: actorId }).onConflictDoNothing();
  }
  await materializePolicies(tx, orgId, taskId, actorId, now);
}

export async function syncPolicyChildren(tx: Tx, orgId: string, parentId: string, items: readonly TaskPolicyItem[], actorId: string, now: Date) {
  for (const item of items) {
    if (!item.generatedSubtaskId) continue;
    const [child] = await tx.select().from(tasks).where(and(eq(tasks.orgId, orgId), eq(tasks.parentTaskId, parentId), eq(tasks.id, item.generatedSubtaskId), eq(tasks.workflowPolicyChecklistItemId, item.id))).for("update");
    if (!child) throw new GuardError("conflict", "A required policy subtask is missing.");
    const completed = item.checkedAt != null && item.checkedBy != null && item.signedAt != null && item.signedBy != null;
    const status = completed ? "completed" : "not_started";
    if (child.status === status) continue;
    await tx.update(tasks).set({ status, startedAt: completed ? (child.startedAt ?? now) : null, completedAt: completed ? now : null, closedAt: completed ? now : null, dueDateAtClose: completed ? child.dueDate : null, completionSummary: completed ? "Policy requirement checked and signed." : null, updatedAt: now }).where(eq(tasks.id, child.id));
    await recordActivity(tx, { orgId, taskId: child.id, actorId }, [{ kind: completed ? "completed" : "reopened", before: { status: child.status }, after: { status }, note: "Updated from the parent checklist." }], now);
  }
}
export async function deletePolicyChildren(tx: Tx, orgId: string, parentId: string) {
  const children = await tx.select({ id: tasks.id, policy: tasks.workflowPolicyId }).from(tasks).where(and(eq(tasks.orgId, orgId), eq(tasks.parentTaskId, parentId)));
  for (const child of children) if (child.policy) await tx.delete(tasks).where(and(eq(tasks.orgId, orgId), eq(tasks.id, child.id)));
}

/** Apply newly attached automatic policies to open tasks; historical closed tasks are untouched. */
export async function materializeScopePolicies(tx: Tx, viewer: Viewer, scope: { kind: "workspace" | "project" | "goal"; id: string }, now: Date) {
  const placement = scope.kind === "project" ? eq(tasks.projectId, scope.id) : scope.kind === "goal"
    ? sql`${tasks.goalId} in (select g.id from goals g where g.org_id = ${viewer.orgId} and (g.id = ${scope.id} or g.parent_goal_id = ${scope.id}))`
    : undefined;
  const rows = await tx.select({ id: tasks.id, status: tasks.status, policyChecklist: tasks.policyChecklist }).from(tasks)
    .where(and(eq(tasks.orgId, viewer.orgId), isNull(tasks.workflowPolicyId), notInArray(tasks.status, closedStatusKeys(viewer.statuses)), placement))
    .orderBy(asc(tasks.id)).for("update");
  for (const row of rows) {
    await materializePolicies(tx, viewer.orgId, row.id, viewer.userId, now);
    if (statusDef(viewer.statuses, row.status).kind !== "awaiting_approval") continue;
    const [after] = await tx.select({ checklist: tasks.policyChecklist }).from(tasks).where(eq(tasks.id, row.id));
    if (!after || after.checklist.length <= row.policyChecklist.length) continue;
    const status = backToWorkTarget(viewer.statuses);
    await tx.update(tasks).set({ status, approverId: null, updatedAt: now }).where(eq(tasks.id, row.id));
    await recordActivity(tx, { orgId: viewer.orgId, taskId: row.id, actorId: viewer.userId }, [{ kind: "sent_back", before: { status: row.status }, after: { status }, note: "A newly attached mandatory policy must be checked and signed before review." }], now);
  }
}
